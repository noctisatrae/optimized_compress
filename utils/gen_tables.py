# The goal is to automatically generate lookup mappings
#
# mask -> index_to_save
#
# because mask is a small integer, i'd rather use an array directly
#
# mask[0b1011] = (0; 1; 3)
#
# Each entry is the list of BYTE positions that `tbl` (simd.runtime_swizzle)
# should pull to the front of the output: the bytes of every kept lane, in
# order, padded with EMPTY up to the entry width.
#
# EMPTY IS 42. ANY TBL INDEX >= 16 PRODUCES A ZERO BYTE, SO 42 MEANS "THIS
# OUTPUT BYTE IS UNUSED". THOSE BYTES GET OVERWRITTEN BY THE NEXT STORE.
#
# Usage:
#   python3 utils/gen_tables.py                      # all tables to stdout
#   python3 utils/gen_tables.py -o neon/tables.odin  # all tables to a file
#   python3 utils/gen_tables.py --dim 32x4           # only some tables

import argparse
import sys
from enum import Enum

EMPTY = 42  # see the note above: tbl turns any index >= 16 into a 0 byte


class Dim(Enum):
    """A NEON vector shape: (bits per lane, number of lanes). Always 128 bits."""

    D32x4 = (32, 4)
    D16x8 = (16, 8)
    D8x16 = (8, 16)

    @property
    def bits(self) -> int:
        return self.value[0]

    @property
    def lanes(self) -> int:
        return self.value[1]

    @property
    def table_lanes(self) -> int:
        # 16 lanes would need a 65536-entry table, so 8x16 is looked up one
        # 8-lane half at a time.
        return min(self.lanes, 8)

    @property
    def name_suffix(self) -> str:
        return f"{self.bits}x{self.lanes}"

    @property
    def table_name(self) -> str:
        return f"SHUFFLE_{self.name_suffix}"

    @property
    def lane_bytes(self) -> int:
        return self.bits // 8

    @property
    def entry_bytes(self) -> int:
        # Always one full NEON register: `tbl` only has a fast path for 16 bytes.
        return 16

    @property
    def entry_type(self) -> str:
        return f"#simd[{self.entry_bytes}]u8"


def kept_lanes(mask: int, lanes: int) -> list[int]:
    """The lanes whose bit is set in `mask`, in order."""
    return [lane for lane in range(lanes) if (mask >> lane) & 1]


def entry_bytes(mask: int, dim: Dim) -> list[int]:
    """The byte positions for one table entry, padded with EMPTY."""
    out = []
    for lane in kept_lanes(mask, dim.table_lanes):
        first = lane * dim.lane_bytes
        out.extend(range(first, first + dim.lane_bytes))
    return out + [EMPTY] * (dim.entry_bytes - len(out))


def gen_table(dim: Dim) -> str:
    n = dim.table_lanes
    lines = []
    if dim.lanes != n:
        lines.append(f"// Indexed by one {n}-lane half of the movemask at a time. The indices")
        lines.append(f"// point into the low half; add {n} to every index for the high half.")
        lines.append(f"// ({EMPTY} + {n} is still >= 16, so unused bytes stay zero.)")
    lines.append(f"// {dim.lane_bytes} byte(s) per lane; {EMPTY} = unused output byte.")
    lines.append("@(rodata)")
    lines.append(f"{dim.table_name} := [{1 << n}]{dim.entry_type}{{")
    for mask in range(1 << n):
        values = entry_bytes(mask, dim)
        # group the bytes by lane so each lane is easy to spot
        groups = [values[i:i + dim.lane_bytes] for i in range(0, len(values), dim.lane_bytes)]
        body = ",  ".join(", ".join(f"{b:2}" for b in g) for g in groups)
        lines.append(f"\t0b{mask:0{n}b} = {{{body}}},")
    lines.append("}")
    return "\n".join(lines)


def gen_file(dims: list[Dim]) -> str:
    parts = [
        "// Code generated by utils/gen_tables.py. DO NOT EDIT.",
        "package neon",
        *(gen_table(dim) for dim in dims),
    ]
    return "\n\n".join(parts) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate NEON compress shuffle tables as Odin code.")
    parser.add_argument(
        "-o", "--output",
        help="file to write the Odin code to (default: print to stdout)",
    )
    parser.add_argument(
        "--dim",
        nargs="+",
        choices=[dim.name_suffix for dim in Dim],
        help="which tables to generate (default: all)",
    )
    args = parser.parse_args()

    dims = [dim for dim in Dim if args.dim is None or dim.name_suffix in args.dim]
    code = gen_file(dims)

    if args.output is None:
        sys.stdout.write(code)
    else:
        with open(args.output, "w") as f:
            f.write(code)


if __name__ == "__main__":
    main()
